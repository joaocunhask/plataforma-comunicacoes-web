// Schema Postgres da plataforma, portado do SQL Server de produção:
//   dump db/init/ProdSchemaDump/schema-18_09_2026-9h40m.sql
//   + db/changes/2026-09-22_split_funis_atingimento.sql
//   + db/bootstrap/01_complemento_indices_triggers.sql (índices; o trigger vive numa migração SQL)
//
// Os nomes de tabelas e colunas são IGUAIS aos do SQL Server, para o ETL ser 1:1 e os
// checksums compararem tabela a tabela. As tabelas AspNet* são legado do ASP.NET Identity:
// ficam só até a autenticação nova (Better Auth) as substituir.
//
// Mapeamento de tipos: nvarchar/varchar(n)→varchar(n), (max)→text, bit→boolean,
// decimal/numeric→numeric (string, nunca float), datetime/datetime2→timestamp sem fuso
// (preserva os valores tal como estão), datetimeoffset→timestamptz, uniqueidentifier→uuid,
// varbinary→bytea, IDENTITY→generated by default (o ETL insere os ids originais).
import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  char,
  check,
  customType,
  date,
  index,
  integer,
  numeric,
  pgTable,
  primaryKey,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
  varchar,
} from "drizzle-orm/pg-core";

const bytea = customType<{ data: Buffer }>({ dataType: () => "bytea" });

const id = () => integer("id").primaryKey().generatedByDefaultAsIdentity();
const bigId = () => bigint("id", { mode: "number" }).primaryKey().generatedByDefaultAsIdentity();
const ts = (name: string) => timestamp(name, { precision: 3 });
const ts2 = (name: string) => timestamp(name, { precision: 6 });
const money = (name: string) => numeric(name, { precision: 10, scale: 2 });

